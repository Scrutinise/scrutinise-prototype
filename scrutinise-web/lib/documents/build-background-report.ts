// ─────────────────────────────────────────────────────────────────────────────
// 26-T2 §5 (decision 150) — THE BACKGROUND REPORT and THE INTRODUCTORY SUMMARY.
//
//   BACKGROUND REPORT   for a reader who wants the ground the proposal stands on: what was read, what it said, where sources disagree, the
//                       conditions and where they came from, the issues the research flushed out and which actions meet each, the
//                       incentives, and what was considered and not taken.
//   INTRODUCTORY SUMMARY  one page for a reader new to the idea: the problem in the owner's words, the policy, the instruments with one line
//                       each, what it costs if known, what is not yet settled.
//
// ⚠ NEITHER IS GENERATED BY A MODEL. Both ARRANGE the record - the kernel fields, the registry, the notes in the record - so nothing in them
//   comes from a model's general knowledge. Every figure is cited or absent; every source is [Ref: n]. A section with nothing behind it says so.
// ⚠ The issue -> action link is only what a note in the record says (it bears on both). With none recorded the report says "no action is
//   recorded as meeting it" - an honest gap, not a guess. (Lex proposing the links is a later step.)
// ─────────────────────────────────────────────────────────────────────────────

import type { Block, DocumentModel, Run, SourceRef } from './model'
import { snapshotHash, assertRenderableSnapshot, type ProposalSnapshot } from './proposal-snapshot'
import { betaBlocks, draftBanner, fieldByKey, fieldText, headlineCost, type ProposalBuildResult } from './build-proposal'
import { text, numbered, incentiveBlocks, notTakenBlocks, dateWords } from './pack-sections'
import { provisionLine } from '@/lib/lex/action-draft-pure'
import { scheduleCounts, scheduleSentence, STATE_WORDS } from '@/lib/lex/action-touches-pure'

const PREDATES = 'This version of the proposal was stored before this document existed, so the record it holds cannot be arranged here. Generate it from the working draft instead.'
const STANCE: Record<string, string> = { SUPPORTS: 'supports', CONTRADICTS: 'contradicts', CONTEXT: 'context', UNDECIDED: 'undecided' }
const clip = (s: string, n: number) => (s.length > n ? `${s.slice(0, n - 1).trimEnd()}…` : s)

function result(snapshot: ProposalSnapshot, title: string, subtitle: string, sourceLabel: string, blocks: Block[]): ProposalBuildResult {
  const model: DocumentModel = { title: `${snapshot.title} — ${title}`, subtitle, sourceLabel, generatedAt: new Date(snapshot.generatedAt), blocks }
  return { model, fingerprint: snapshotHash(snapshot), sourceLabel }
}

export function buildBackgroundReport(snapshot: ProposalSnapshot): ProposalBuildResult {
  assertRenderableSnapshot(snapshot)
  const blocks: Block[] = [...draftBanner(snapshot), ...betaBlocks()]
  const data = snapshot.actionsPack
  if (!data) {
    blocks.push({ kind: 'note', text: PREDATES })
    return result(snapshot, 'Background Report', 'The ground this proposal stands on.', 'the record of this proposal', blocks)
  }

  // ── 1 · what was read ──
  blocks.push({ kind: 'section', title: 'WHAT WAS READ' })
  const kinds = new Map<string, number>()
  for (const s of data.registry) kinds.set(s.kind, (kinds.get(s.kind) ?? 0) + 1)
  const KIND: Record<string, string> = { CORPUS: 'from the legislation and parliamentary corpus', URL: 'web pages', DOCUMENT: 'documents filed by the owner', OWN_OBSERVATION: 'the owner’s own observations' }
  blocks.push(numbered('1.1', [{ text: `${data.registry.length} ${data.registry.length === 1 ? 'source is' : 'sources are'} in the numbered list` + (kinds.size ? `: ${[...kinds.entries()].map(([k, n]) => `${n} ${KIND[k] ?? k.toLowerCase()}`).join(', ')}.` : '.') }]))
  if (data.registry.length) {
    blocks.push({ kind: 'bullets', items: data.registry.map((s): Run[] => [{ text: `[Ref: ${s.number}] `, bold: true }, { text: s.title }, ...(s.citation ? [{ text: ` — ${s.citation}`, italic: true }] : [])]) })
  }

  // ── 2 · what it said ──
  blocks.push({ kind: 'section', title: 'WHAT IT SAID' })
  if (data.notes.length) {
    blocks.push({ kind: 'note', text: 'Notes the owner has put in the record, each with the source it cites and what it bears on. A note the owner has not yet put in the record, or has set aside, is not printed here (set-aside notes appear under “Considered, not taken”).' })
    data.notes.forEach((n, i) => blocks.push(numbered(`2.${i + 1}`, [
      ...(n.quote ? [{ text: `“${clip(n.quote, 500)}”`, italic: true }, { text: ' ' }] : []),
      ...(n.text ? [{ text: clip(n.text, 800) }] : []),
      { text: ` — ${STANCE[n.stance] ?? n.stance}${n.bearsOn.length ? `; bears on ${n.bearsOn.join('; ')}` : ''}; ${n.author}, ${dateWords(n.at)}` + (n.ref != null ? ` [Ref: ${n.ref}]` : ''), italic: true },
    ])))
  } else blocks.push(numbered('2.1', [{ text: 'No notes are in the record yet.', italic: true }]))

  // ── 3 · where the sources disagree ──
  blocks.push({ kind: 'section', title: 'WHERE SOURCES DISAGREE' })
  const contradicting = (snapshot.evidence ?? []).filter((e) => e.kind === 'CONTRADICTS')
  if (data.disagreements.length || contradicting.length) {
    let i = 0
    for (const d of data.disagreements) blocks.push(numbered(`3.${++i}`, [{ text: `On ${d.on}: `, bold: true }, { text: d.between.join(' | ') }]))
    for (const e of contradicting) blocks.push(numbered(`3.${++i}`, [{ text: `${e.title}: `, bold: true }, { text: clip(e.body, 500) }, { text: ' — a finding marked as contradicting', italic: true }, ...(e.ref != null ? [{ text: ` [Ref: ${e.ref}]` }] : [])]))
  } else blocks.push(numbered('3.1', [{ text: 'No note or finding in the record is marked as contradicting another.', italic: true }]))

  // ── 4 · the conditions, and where they came from ──
  blocks.push({ kind: 'section', title: 'THE CONDITIONS' })
  if (data.conditions.length) {
    data.conditions.forEach((c) => blocks.push(numbered(`4.${c.number}`, [{ text: `Condition ${c.number}: `, bold: true }, { text: c.text }])))
    blocks.push({ kind: 'note', text: data.conditionsSource ? `Where the list came from: ${data.conditionsSource}` : 'The record does not say where this list came from.' })
    const uncovered = data.conditions.filter((c) => !data.actions.some((a) => a.conditionNumbers.includes(c.number)))
    blocks.push({ kind: 'paragraph', runs: text(uncovered.length ? `${uncovered.length} of ${data.conditions.length} conditions have no action recorded as delivering them: ${uncovered.map((c) => c.number).join(', ')}.` : `Every one of the ${data.conditions.length} conditions has at least one action recorded as delivering it.`) })
  } else blocks.push(numbered('4.1', [{ text: 'The owner has recorded no conditions.', italic: true }]))

  // ── 5 · the issues the research flushed out, and which actions meet each ──
  blocks.push({ kind: 'section', title: 'ISSUES AND THE ACTIONS THAT MEET THEM' })
  if (data.issueActions.length) {
    blocks.push({ kind: 'note', text: 'An action is shown against an issue only where a note in the record bears on both. “No action is recorded as meeting it” means nobody has recorded one, not that none does.' })
    data.issueActions.forEach((x, i) => blocks.push(numbered(`5.${i + 1}`, [{ text: clip(x.issue, 400), bold: true }, { text: x.actionNumbers.length ? ` — met by ${x.actionNumbers.map((n) => `#${n}`).join(', ')}` : ' — no action is recorded as meeting it', italic: !x.actionNumbers.length }])))
  } else blocks.push(numbered('5.1', [{ text: 'The research has raised no open issue on this proposal.', italic: true }]))

  // ── 6 · incentives ──
  blocks.push({ kind: 'section', title: 'INCENTIVES' })
  blocks.push(...incentiveBlocks(data.actions))

  // ── 7 · considered, not taken ──
  blocks.push({ kind: 'section', title: 'CONSIDERED, NOT TAKEN' })
  blocks.push(...notTakenBlocks(data, { includeNotebook: true }))

  // ── 8 · 26-U §4c — what the drafted clauses touch (the consequential schedule's counts) and the precedents they draw on ──
  blocks.push({ kind: 'section', title: 'WHAT THE DRAFTED CLAUSES TOUCH' })
  const drafted = data.actions.filter((a) => a.draft)
  if (!drafted.length) blocks.push(numbered('8.1', [{ text: data.actions.some((a) => 'draft' in a) ? 'No action has a drafting instruction yet.' : 'This version of the proposal was stored before drafting instructions existed.', italic: true }]))
  else {
    const touches = drafted.flatMap((a) => a.touches ?? [])
    blocks.push(numbered('8.1', [{ text: `${drafted.length} ${drafted.length === 1 ? 'action has' : 'actions have'} a drafting instruction. ` }, { text: scheduleSentence(scheduleCounts(touches)) }]))
    const named = touches.filter((t) => t.state !== 'held')
    if (named.length) blocks.push(numbered('8.2', [{ text: 'Named but not computed: ', bold: true }, { text: named.map((t) => `${provisionLine(t.line)} — ${STATE_WORDS[t.state]}`).join('; ') }]))
    const prec = drafted.flatMap((a) => (a.draft?.precedents ?? []).map((p) => ({ a, p })))
    blocks.push(numbered('8.3', [{ text: 'Precedents drawn on: ', bold: true }, prec.length ? { text: prec.map(({ a, p }) => `#${a.number} — ${p.docUri}${p.provisionPath ? ` ${p.provisionPath}` : ''} (${p.how})`).join('; ') } : { text: 'none recorded in the drafting instructions.', italic: true }]))
  }

  // ── the numbered sources ──
  blocks.push({ kind: 'section', title: 'SOURCES' })
  if (data.registry.length) {
    const refs: SourceRef[] = data.registry.map((s) => ({ ref: s.number, title: s.title, citation: s.citation ?? '', url: s.url ?? '' }))
    blocks.push({ kind: 'sources', label: `All sources (${refs.length})`, refs })
  } else blocks.push({ kind: 'paragraph', runs: text('No sources are registered on this proposal.') })
  return result(snapshot, 'Background Report', 'The ground this proposal stands on: what was read, what it said, where it disagrees, and what was set aside.', 'the numbered sources, the notes in the record and the actions of this proposal', blocks)
}

export function buildIntroductorySummary(snapshot: ProposalSnapshot): ProposalBuildResult {
  assertRenderableSnapshot(snapshot)
  const blocks: Block[] = [...draftBanner(snapshot), ...betaBlocks()]
  const data = snapshot.actionsPack

  blocks.push({ kind: 'heading', level: 2, runs: text('The problem') })
  const challenge = fieldText(fieldByKey(snapshot, 'challenge'))
  blocks.push({ kind: 'paragraph', runs: text(challenge ? clip(challenge, 600) : 'Not yet settled on this proposal.') })

  blocks.push({ kind: 'heading', level: 2, runs: text('The policy') })
  const chosen = (snapshot.options ?? []).find((o) => o.status === 'CHOSEN')
  blocks.push({ kind: 'paragraph', runs: text(chosen ? clip(chosen.approach, 600) : 'No Guiding Policy has been settled yet.') })

  blocks.push({ kind: 'heading', level: 2, runs: text('The instruments') })
  if (data && data.headings.length) {
    const counted = data.headings.map((h) => ({ h, n: data.actions.filter((a) => a.headingId === h.id).length }))
    blocks.push({ kind: 'bullets', items: counted.map(({ h, n }): Run[] => [{ text: h.name, bold: true }, { text: ` — ${h.purpose ? clip(h.purpose.split(/(?<=[.!?])\s/)[0], 160) : 'purpose not yet written'} (${n} ${n === 1 ? 'action' : 'actions'})` }]) })
    const unsorted = data.actions.filter((a) => a.headingId == null).length
    if (unsorted) blocks.push({ kind: 'note', text: `${unsorted} ${unsorted === 1 ? 'action is' : 'actions are'} not yet under any heading.` })
  } else if (data) blocks.push({ kind: 'paragraph', runs: text(data.actions.length ? `${data.actions.length} actions, not yet sorted under headings.` : 'No actions yet.') })
  else blocks.push({ kind: 'note', text: PREDATES })

  blocks.push({ kind: 'heading', level: 2, runs: text('What it costs') })
  const cost = headlineCost(snapshot.actions ?? [])
  blocks.push({ kind: 'paragraph', runs: text(cost ? `The cost to implement, added up across every action (each has a figure recorded): ${cost}.` : 'No total cost is recorded yet. A figure appears here only when every action has been costed or marked as having no cost.') })

  blocks.push({ kind: 'heading', level: 2, runs: text('What is not yet settled') })
  const out = snapshot.outstanding
  const items: string[] = []
  if (!chosen) items.push('the Guiding Policy')
  if (out?.counts.openIssues) items.push(`${out.counts.openIssues} open ${out.counts.openIssues === 1 ? 'challenge' : 'challenges'}`)
  if (out?.counts.unresolvedForks) items.push(`${out.counts.unresolvedForks} ${out.counts.unresolvedForks === 1 ? 'decision' : 'decisions'} still open`)
  if (data) {
    const unanswered = data.actions.filter((a) => !a.slots.who || !a.slots.against).length
    if (unanswered) items.push(`${unanswered} of ${data.actions.length} actions are missing who will do them or what will oppose them`)
    const noCond = data.conditions.filter((c) => !data.actions.some((a) => a.conditionNumbers.includes(c.number))).length
    if (noCond) items.push(`${noCond} of ${data.conditions.length} conditions have no action delivering them`)
  }
  blocks.push(items.length ? { kind: 'bullets', items: items.map((s): Run[] => text(s)) } : { kind: 'paragraph', runs: text('Nothing recorded as unsettled.') })

  return result(snapshot, 'Introductory Summary', 'One page for a reader new to this proposal.', 'the kernel of this proposal (written by the owner, not by a model)', blocks)
}
