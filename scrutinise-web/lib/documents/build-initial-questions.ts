// ─────────────────────────────────────────────────────────────────────────────
// INITIAL QUESTIONS — the briefing's companion (17 Sep 2026, pilot feedback, Angus Barry).
//
// The Initial Background Briefing is "here is what we found". This is "here is what we need
// from you": everything the first pass of ONE BUILD needs from the user, grouped —
//
//   1. decisions awaiting them — the kernel fields not yet settled, and what each choice
//      rules out;
//   2. choices between causes and between candidate approaches;
//   3. what the corpus could not answer, and what kind of gap each is;
//   4. what the user knows that we do not — the testimony gaps;
//   5. challenges that need a response.
//
// ⚠⚠ EVERY ITEM STATES WHAT WOULD RESOLVE IT. 25-V §8: *"A question with no route to an
// answer is a complaint, not a question."* The route is the honest one, not a hopeful one —
// a fork is open because the corpus did NOT decide it, so what settles it is the proposer
// choosing, and promising that more searching would is a promise this product cannot keep.
// `RESOLVES` below is the one place the routes are written; `check:export` asserts every
// rendered item carries one.
//
// ⚠ IT IS STATIC, AND STAMPED WITH THE BUILD. Composed from the build's own rows the moment
// the build settles (`snapshotInitialQuestions`, called from `finishBuild`) and stored as a
// `Document` row with `buildId`/`buildVersion` — the same stamp the briefing carries, so the
// pair reads as one thing. Regeneration re-renders the stored body; it never recomposes.
// The LIVE view of the same material is the worklist in the working area (`lib/lex/agenda.ts`
// → `WorkList.tsx`); this is the record of what the build asked for, frozen.
//
// ⚠ A build that finished before this existed gets its snapshot composed on first read
// (`ensureInitialQuestions`) from its rows AS THEY STAND THEN — and the document says so,
// because a fork the user has since resolved is not "awaiting" them and the label must not
// pretend it was frozen at the build. Nothing is generated by a model anywhere in this file.
// ─────────────────────────────────────────────────────────────────────────────

